"""
Raw data generator for the cluster_pipeline project.

Creates deliberately messy "raw" data in data/raw/ that imitates what a real
cluster-monitoring setup produces:

    servers_inventory.csv        - server list exported from a spreadsheet
    metrics_YYYY-MM-DD.jsonl     - one JSON object per line, one file per day
    cluster_events.log           - plain-text log lines from many services

Usage (from the project root):

    python generate_raw_data.py

Do NOT edit this file and do NOT fix the raw files by hand.
Your job is to build the pipeline on top of its output.
The seed is fixed, so everyone gets exactly the same data.
"""

import csv
import json
import math
import random
from datetime import datetime, timedelta, timezone
from pathlib import Path

SEED = 42
random.seed(SEED)

RAW_DIR = Path(__file__).parent / "data" / "raw"
RAW_DIR.mkdir(parents=True, exist_ok=True)

N_SERVERS = 120
CLUSTERS = ["alpha", "beta", "gamma", "delta"]
OS_LIST = ["Ubuntu 22.04", "Ubuntu 20.04", "Debian 12", "CentOS 7", "RHEL 9"]
START = datetime(2026, 10, 1)
DAYS = 7
STEP_MINUTES = 15
N_EVENTS = 5000


# --------------------------------------------------------------------------
# helpers
# --------------------------------------------------------------------------
def server_id(i):
    return f"srv-{i:03d}"


def id_variant(sid):
    """Same server, written in different ways by different systems."""
    r = random.random()
    if r < 0.80:
        return sid
    if r < 0.88:
        return sid.upper()
    if r < 0.95:
        return sid.replace("-", "")
    return f" {sid} "


def clamp(x, lo=0.0, hi=100.0):
    return max(lo, min(hi, x))


# --------------------------------------------------------------------------
# 1. servers_inventory.csv
# --------------------------------------------------------------------------
def build_servers():
    servers = []
    for i in range(1, N_SERVERS + 1):
        cluster = CLUSTERS[(i - 1) % len(CLUSTERS)]
        node_no = (i - 1) // len(CLUSTERS) + 1
        servers.append(
            {
                "i": i,
                "sid": server_id(i),
                "cluster": cluster,
                "hostname": f"{cluster}-node-{node_no:02d}",
                "rack": f"R{random.randint(1, 12):02d}",
                "os": random.choice(OS_LIST),
                "cpu_cores": random.choice([8, 16, 32, 64]),
                "ram_gb": random.choice([32, 64, 128, 256]),
                "purchased": datetime(2020, 1, 1)
                + timedelta(days=random.randint(0, 6 * 365)),
                "status": random.choices(
                    ["active", "maintenance", "decommissioned"], [90, 6, 4]
                )[0],
            }
        )
    return servers


STATUS_VARIANTS = {
    "active": ["active", "Active", "ACTIVE", "up", "Up "],
    "maintenance": ["maintenance", "maint", "Maintenance"],
    "decommissioned": ["decommissioned", "down", "Decommissioned", "retired"],
}


def date_variant(d):
    r = random.random()
    if r < 0.60:
        return d.strftime("%Y-%m-%d")
    if r < 0.80:
        return d.strftime("%d/%m/%Y")
    if r < 0.90:
        return d.strftime("%b %d, %Y")
    return d.strftime("%d.%m.%Y")


def write_inventory(servers):
    header = [
        "server_id",
        "Hostname",
        "cluster ",
        "rack",
        "OS",
        "cpu_cores",
        "RAM",
        "purchase_date",
        "status",
    ]
    rows = []
    for s in servers:
        hostname = s["hostname"]
        r = random.random()
        if r < 0.10:
            hostname = hostname.upper()
        elif r < 0.18:
            hostname = hostname + " "
        elif r < 0.22:
            hostname = hostname.title()

        cluster = s["cluster"]
        r = random.random()
        if r < 0.08:
            cluster = cluster.capitalize()
        elif r < 0.12:
            cluster = cluster.upper() + " "
        elif r < 0.14:
            cluster = "alfa" if cluster == "alpha" else cluster

        rack = s["rack"] if random.random() > 0.05 else ""

        cores = s["cpu_cores"]
        if random.random() < 0.04:
            cores = random.choice(["", "N/A"])

        ram = s["ram_gb"]
        r = random.random()
        if r < 0.04:
            ram = random.choice(["", "N/A"])
        elif r < 0.30:
            ram = f"{ram}GB"
        elif r < 0.45:
            ram = f"{ram} GB"

        rows.append(
            [
                id_variant(s["sid"]) if random.random() < 0.25 else s["sid"],
                hostname,
                cluster,
                rack,
                s["os"],
                cores,
                ram,
                date_variant(s["purchased"]),
                random.choice(STATUS_VARIANTS[s["status"]]),
            ]
        )

    # a few impossible values
    rows[17][5] = 0
    rows[63][5] = 9999
    rows[88][7] = "2031-02-30"
    rows[101][7] = "0000-00-00"

    # duplicates: some exact copies, some where one field differs
    for idx in random.sample(range(len(rows)), 6):
        dup = list(rows[idx])
        if random.random() < 0.5:
            dup[8] = random.choice(["active", "maint", "up"])
        rows.append(dup)

    random.shuffle(rows)
    with open(RAW_DIR / "servers_inventory.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)
    return len(rows)


# --------------------------------------------------------------------------
# 2. metrics_YYYY-MM-DD.jsonl
# --------------------------------------------------------------------------
def ts_variant(ts):
    r = random.random()
    if r < 0.82:
        return ts.strftime("%Y-%m-%dT%H:%M:%S")
    if r < 0.92:
        return ts.strftime("%Y-%m-%d %H:%M:%S")
    if r < 0.96:
        return int(ts.replace(tzinfo=timezone.utc).timestamp())
    return ts.strftime("%d/%m/%Y %H:%M")


def corrupt(val, kind):
    r = random.random()
    if r < 0.010:
        return None
    if r < 0.015:
        return "N/A"
    if r < 0.018:
        return -abs(val) - 1
    if r < 0.021:
        return round(random.uniform(120, 400), 1) if kind == "pct" else 99999.0
    if r < 0.041:
        return str(val)
    return val


def write_metrics(servers):
    profiles = {
        s["sid"]: {
            "cpu": random.uniform(15, 70),
            "mem": random.uniform(30, 80),
            "disk": random.uniform(20, 70),
            "net": random.uniform(50, 400),
        }
        for s in servers
    }
    # a few servers go silent for several hours on day 2
    outage = set(random.sample([s["sid"] for s in servers], 3))

    total = 0
    for day in range(DAYS):
        day_start = START + timedelta(days=day)
        lines = []
        steps = 24 * 60 // STEP_MINUTES
        for step in range(steps):
            ts = day_start + timedelta(minutes=step * STEP_MINUTES)
            wave = math.sin((ts.hour - 8) / 24 * 2 * math.pi)
            for s in servers:
                sid = s["sid"]
                if sid in outage and day == 1 and 2 <= ts.hour < 9:
                    continue
                if random.random() < 0.01:  # random gaps
                    continue

                p = profiles[sid]
                cpu = round(clamp(p["cpu"] + 12 * wave + random.gauss(0, 6)), 1)
                mem = round(clamp(p["mem"] + random.gauss(0, 3)), 1)
                disk = round(clamp(p["disk"] + day * 0.4 + random.gauss(0, 0.3)), 1)
                net_in = round(max(0, p["net"] * (1 + 0.3 * wave) + random.gauss(0, 20)), 1)
                net_out = round(max(0, net_in * random.uniform(0.3, 0.8)), 1)

                rec = {
                    "server_id": id_variant(sid),
                    "ts": ts_variant(ts),
                    "cpu_pct": corrupt(cpu, "pct"),
                    "mem_pct": corrupt(mem, "pct"),
                    "disk_pct": corrupt(disk, "pct"),
                    "net_in_mbps": corrupt(net_in, "net"),
                    "net_out_mbps": corrupt(net_out, "net"),
                }

                if random.random() < 0.003:  # server id nobody knows
                    rec["server_id"] = f"srv-{random.randint(150, 199)}"
                if random.random() < 0.005:  # a field is missing completely
                    del rec[random.choice(["cpu_pct", "mem_pct", "disk_pct", "net_in_mbps", "net_out_mbps"])]

                if day == 3:  # schema drift: a deploy renamed some keys
                    rec = {
                        {"cpu_pct": "cpu_usage", "mem_pct": "memory_pct", "ts": "timestamp"}.get(k, k): v
                        for k, v in rec.items()
                    }

                line = json.dumps(rec)
                if random.random() < 0.0007:  # broken / truncated line
                    line = line[: random.randint(10, len(line) - 5)]
                lines.append(line)
                if random.random() < 0.005:  # duplicate delivery
                    lines.append(line)

        path = RAW_DIR / f"metrics_{day_start.strftime('%Y-%m-%d')}.jsonl"
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        total += len(lines)
    return total


# --------------------------------------------------------------------------
# 3. cluster_events.log
# --------------------------------------------------------------------------
SERVICES = ["nginx", "postgres", "redis", "kubelet", "docker", "sshd", "prometheus-node"]
HOSTS = ["db-main", "cache-01", "api-gateway", "storage-02"]

TEMPLATES = {
    "INFO": [
        "service {svc} restarted",
        "reboot completed",
        "backup completed in {n}s",
        "health check passed",
        "config reloaded",
    ],
    "WARN": [
        "disk usage at {pct}%",
        "high cpu load {pct}%",
        "slow response {ms}ms",
        "memory usage at {pct}%",
    ],
    "ERROR": [
        "service {svc} failed to start",
        "connection timeout to {host}",
        "out of memory",
        "failed health check ({svc})",
    ],
    "CRITICAL": [
        "node unreachable",
        "disk failure detected",
        "kernel panic",
    ],
}


def write_events(servers):
    problem = random.sample([s["sid"] for s in servers], 8)
    weights = {s["sid"]: (6 if s["sid"] in problem else 1) for s in servers}
    sids = list(weights)
    w = list(weights.values())

    span = DAYS * 24 * 3600
    events = []
    for _ in range(N_EVENTS):
        ts = START + timedelta(seconds=random.randint(0, span - 1))
        sid = random.choices(sids, w)[0]
        level = random.choices(
            ["INFO", "WARN", "ERROR", "CRITICAL"],
            [55, 25, 17, 3] if sid not in problem else [30, 30, 32, 8],
        )[0]
        msg = random.choice(TEMPLATES[level]).format(
            svc=random.choice(SERVICES),
            n=random.randint(5, 900),
            pct=random.randint(70, 99),
            ms=random.randint(300, 9000),
            host=random.choice(HOSTS),
        )
        events.append((ts, sid, level, msg))
    events.sort(key=lambda e: e[0])

    lines = []
    for ts, sid, level, msg in events:
        r = random.random()
        if r < 0.70:
            line = f"{ts:%Y-%m-%d %H:%M:%S} [{level}] {sid} {msg}"
        elif r < 0.85:
            line = f"{ts:%Y-%m-%dT%H:%M:%SZ} {level} {sid.replace('-', '')}: {msg}"
        elif r < 0.95:
            line = f"{ts:%d/%m/%Y %H:%M:%S} | {level.lower()} | {sid.upper()} | {msg}"
        else:
            line = f"{ts:%Y-%m-%d %H:%M:%S} [{level}] {msg}"  # no server at all

        lines.append(line)
        r = random.random()
        if r < 0.01:
            lines.append("")
        elif r < 0.02:
            lines.append("-" * 40)
        elif r < 0.03:
            lines.append("Traceback (most recent call last):")
        elif r < 0.035:
            lines.append(line[: random.randint(8, 25)])  # truncated

    (RAW_DIR / "cluster_events.log").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(lines)


# --------------------------------------------------------------------------
if __name__ == "__main__":
    servers = build_servers()
    n_inv = write_inventory(servers)
    n_met = write_metrics(servers)
    n_log = write_events(servers)
    print(f"servers_inventory.csv : {n_inv} data rows")
    print(f"metrics_*.jsonl       : {n_met} lines in {DAYS} files")
    print(f"cluster_events.log    : {n_log} lines")
    print(f"written to            : {RAW_DIR}")
